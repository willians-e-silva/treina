/**
 * Generates `src/theme/colors.ts`: the Material 3 color scheme (light and
 * dark) of the app, built from the colors of `assets/images/icon.png`.
 *
 *   node scripts/generate-theme.mjs           # writes src/theme/colors.ts
 *   node scripts/generate-theme.mjs --report  # also prints the contrast table
 *
 * The seed is the icon's blue (the color `Score` ranks first among the
 * icon's quantized colors, the same pick Android makes from a wallpaper).
 * The scheme follows the `Fidelity` variant, which keeps the seed's chroma so
 * the app is as vivid as the icon, except that tertiary comes from the
 * icon's purple instead of a computed complement.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import {
  argbFromHex,
  Contrast,
  customColor,
  DynamicScheme,
  Hct,
  hexFromArgb,
  MaterialDynamicColors,
  TonalPalette,
} from '@material/material-color-utilities';

/** `Variant.FIDELITY`: the enum is not exported by the package in 0.3.0. */
const VARIANT_FIDELITY = 5;

/** Colors measured in icon.png (Celebi quantization, 32 colors). */
const ICON = {
  /** Seed: blue petal (dumbbell). */
  blue: '#0D9BF8',
  /** Purple petal (checklist), count-weighted mean of its clusters. */
  purple: '#6C3CF4',
  /** Green petal (cutlery), count-weighted mean of its clusters. */
  green: '#2AB868',
  /** Background, mean of a 24px ring along the edges. */
  background: '#090F19',
};

/**
 * Extra colors with their own roles. `blend: false` keeps the icon's hue;
 * the chart colors are harmonized (hue nudged toward the seed).
 */
const CUSTOM = [
  { name: 'diet', value: ICON.green, blend: false },
  { name: 'carbs', value: '#12A594', blend: true },
  { name: 'protein', value: '#F76B15', blend: true },
  { name: 'fat', value: '#8E4EC6', blend: true },
  { name: 'steps', value: '#3E63DD', blend: true },
  { name: 'exercise', value: '#E5484D', blend: true },
];

const ROLES = [
  'primary',
  'onPrimary',
  'primaryContainer',
  'onPrimaryContainer',
  'inversePrimary',
  'secondary',
  'onSecondary',
  'secondaryContainer',
  'onSecondaryContainer',
  'tertiary',
  'onTertiary',
  'tertiaryContainer',
  'onTertiaryContainer',
  'error',
  'onError',
  'errorContainer',
  'onErrorContainer',
  'background',
  'onBackground',
  'surface',
  'onSurface',
  'surfaceVariant',
  'onSurfaceVariant',
  'surfaceDim',
  'surfaceBright',
  'surfaceContainerLowest',
  'surfaceContainerLow',
  'surfaceContainer',
  'surfaceContainerHigh',
  'surfaceContainerHighest',
  'inverseSurface',
  'inverseOnSurface',
  'outline',
  'outlineVariant',
  'shadow',
  'scrim',
  'surfaceTint',
];

function scheme(isDark) {
  const seed = Hct.fromInt(argbFromHex(ICON.blue));
  return new DynamicScheme({
    sourceColorArgb: seed.toInt(),
    variant: VARIANT_FIDELITY,
    contrastLevel: 0,
    isDark,
    primaryPalette: TonalPalette.fromHueAndChroma(seed.hue, seed.chroma),
    secondaryPalette: TonalPalette.fromHueAndChroma(
      seed.hue,
      Math.max(seed.chroma - 32, seed.chroma * 0.5),
    ),
    tertiaryPalette: TonalPalette.fromInt(argbFromHex(ICON.purple)),
    neutralPalette: TonalPalette.fromHueAndChroma(seed.hue, seed.chroma / 8),
    neutralVariantPalette: TonalPalette.fromHueAndChroma(seed.hue, seed.chroma / 8 + 4),
  });
}

function roles(isDark) {
  const s = scheme(isDark);
  return Object.fromEntries(
    ROLES.map((role) => [role, hexFromArgb(MaterialDynamicColors[role].getArgb(s)).toUpperCase()]),
  );
}

function customRoles(isDark) {
  const source = argbFromHex(ICON.blue);
  return Object.fromEntries(
    CUSTOM.map((color) => {
      const group = customColor(source, { ...color, value: argbFromHex(color.value) });
      const tones = isDark ? group.dark : group.light;
      return [
        color.name,
        Object.fromEntries(
          Object.entries(tones).map(([role, argb]) => [role, hexFromArgb(argb).toUpperCase()]),
        ),
      ];
    }),
  );
}

const light = roles(false);
const dark = roles(true);
const customLight = customRoles(false);
const customDark = customRoles(true);

const json = (value) => JSON.stringify(value, null, 2).replace(/"(\w+)":/g, '$1:');

const output = `/**
 * Material 3 color roles of the app, light and dark.
 *
 * GENERATED by \`node scripts/generate-theme.mjs\` from the colors of
 * \`assets/images/icon.png\`. Do not edit by hand: change the script and run
 * it again.
 */

/** Colors measured in the app icon. */
export const IconColors = ${json(ICON)} as const;

export const LightColors = ${json(light)} as const;

export const DarkColors = ${json(dark)} as const;

/**
 * Custom colors (M3 "custom color" roles): \`color\` for marks and text,
 * \`onColor\` on top of it, \`colorContainer\` / \`onColorContainer\` for
 * tinted backgrounds.
 */
export const LightCustomColors = ${json(customLight)} as const;

export const DarkCustomColors = ${json(customDark)} as const;

export type ColorRole = keyof typeof LightColors;
export type CustomColorName = keyof typeof LightCustomColors;
`;

const target = fileURLToPath(new URL('../src/theme/colors.ts', import.meta.url));
writeFileSync(target, output);
console.log(`Wrote ${target}`);

if (process.argv.includes('--report')) {
  const ratio = (fg, bg) =>
    Contrast.ratioOfTones(Hct.fromInt(argbFromHex(fg)).tone, Hct.fromInt(argbFromHex(bg)).tone);
  /** [foreground, background, minimum ratio, what it is] */
  const pairs = [
    ['onPrimary', 'primary', 4.5, 'texto do botão filled (ação principal)'],
    ['onPrimaryContainer', 'primaryContainer', 4.5, 'texto do FAB estendido'],
    ['onSecondaryContainer', 'secondaryContainer', 4.5, 'botão tonal / chip e segmento selecionados'],
    ['onTertiaryContainer', 'tertiaryContainer', 4.5, 'iniciais do avatar'],
    ['onSurface', 'surface', 4.5, 'texto principal'],
    ['onSurfaceVariant', 'surface', 4.5, 'texto secundário'],
    ['onSurface', 'surfaceContainer', 4.5, 'texto em card'],
    ['onSurfaceVariant', 'surfaceContainer', 4.5, 'texto secundário em card / rótulo da barra'],
    ['onSurface', 'surfaceContainerHighest', 4.5, 'texto digitado em campo'],
    ['onSurfaceVariant', 'surfaceContainerHighest', 4.5, 'placeholder em campo'],
    ['onSurfaceVariant', 'surfaceContainerHigh', 4.5, 'placeholder da busca'],
    ['onSurface', 'surfaceContainerHigh', 4.5, 'título de diálogo'],
    ['secondary', 'surface', 4.5, 'botão text secundário (links)'],
    ['error', 'surface', 4.5, 'mensagem de erro / botão Sair'],
    ['error', 'surfaceContainer', 4.5, 'calorias acima da meta (card)'],
    ['onPrimaryContainer', 'primaryContainer', 3, 'ícone do FAB'],
    ['secondary', 'surfaceContainer', 3, 'checkbox/radio marcado em card'],
    ['outline', 'surface', 3, 'borda de segmented button'],
    ['onSurfaceVariant', 'surfaceContainer', 3, 'ícone inativo da barra inferior'],
    ['onSecondaryContainer', 'secondaryContainer', 3, 'ícone ativo da barra inferior'],
    ['primary', 'surfaceContainerHighest', 3, 'indicador de foco do campo'],
    ['tertiary', 'surfaceContainer', 3, 'linha do gráfico de peso'],
  ];
  for (const [mode, colors, custom] of [
    ['CLARO', light, customLight],
    ['ESCURO', dark, customDark],
  ]) {
    console.log(`\n${mode}`);
    for (const [fg, bg, min, label] of pairs) {
      const r = ratio(colors[fg], colors[bg]);
      console.log(
        `${r >= min ? 'OK  ' : 'FAIL'} ${r.toFixed(2).padStart(5)}:1 (mín ${min}) ${fg} ${colors[fg]} / ${bg} ${colors[bg]} — ${label}`,
      );
    }
    for (const [name, c] of Object.entries(custom)) {
      for (const bg of ['surface', 'surfaceContainer']) {
        const r = ratio(c.color, colors[bg]);
        console.log(
          `${r >= 3 ? 'OK  ' : 'FAIL'} ${r.toFixed(2).padStart(5)}:1 (mín 3) ${name} ${c.color} / ${bg} ${colors[bg]} — gráfico/ícone`,
        );
      }
    }
  }
  // Google sign-in button: fixed brand colors from src/theme (BrandColors).
  const google = [
    ['CLARO', '#1F1F1F', '#FFFFFF'],
    ['ESCURO', '#E3E3E3', '#131314'],
  ];
  console.log('\nGOOGLE (cores da marca)');
  for (const [mode, fg, bg] of google) {
    const r = ratio(fg, bg);
    console.log(`${r >= 4.5 ? 'OK  ' : 'FAIL'} ${r.toFixed(2).padStart(5)}:1 (mín 4.5) ${fg} / ${bg} — texto do botão Google (${mode})`);
  }
}
