/**
 * Writes supabase/seed.sql with the trainer catalog of src/lib/trainers.ts.
 * Ids come from the slugs (md5), so running the seed again updates the same
 * rows instead of adding new ones.
 *
 *   npx tsx scripts/generate-seed.ts
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { searchTrainers } from '../src/lib/trainers';

const text = (value: string | undefined) =>
  value === undefined ? 'null' : `'${value.replaceAll("'", "''")}'`;
const id = (key: string) => `md5(${text(key)})::uuid`;

const trainers = searchTrainers('');
const lines: string[] = [
  '-- Generated by scripts/generate-seed.ts from src/lib/trainers.ts; do not edit.',
  '-- Trainer catalog: trainers, their packages, the packages\' workouts and comments.',
  '',
];

trainers.forEach((trainer, trainerIndex) => {
  lines.push(
    `insert into public.trainers (id, slug, name, photo_url, instagram, specialty, bio, followers, rating, rating_count, students, position)`,
    `values (${id(`trainer:${trainer.id}`)}, ${text(trainer.id)}, ${text(trainer.name)}, ${text(trainer.photoUrl)}, ${text(trainer.instagram)}, ${text(trainer.specialty)}, ${text(trainer.bio)}, ${trainer.followers}, ${trainer.rating}, ${trainer.ratingCount}, ${trainer.students}, ${trainerIndex})`,
    `on conflict (slug) do update set name = excluded.name, photo_url = excluded.photo_url, instagram = excluded.instagram, specialty = excluded.specialty, bio = excluded.bio, followers = excluded.followers, rating = excluded.rating, rating_count = excluded.rating_count, students = excluded.students, position = excluded.position;`,
    '',
  );

  trainer.packages.forEach((pkg, packageIndex) => {
    const packageId = id(`package:${pkg.id}`);
    lines.push(
      `insert into public.training_packages (id, slug, trainer_id, name, description, level, weeks, position)`,
      `values (${packageId}, ${text(pkg.id)}, ${id(`trainer:${trainer.id}`)}, ${text(pkg.name)}, ${text(pkg.description)}, ${text(pkg.level)}, ${pkg.weeks}, ${packageIndex})`,
      `on conflict (slug) do update set trainer_id = excluded.trainer_id, name = excluded.name, description = excluded.description, level = excluded.level, weeks = excluded.weeks, position = excluded.position;`,
      '',
    );

    pkg.workouts.forEach((workout, position) => {
      // Notes left out of an exercise are dropped by JSON.stringify.
      lines.push(
        `insert into public.package_workouts (id, package_id, position, name, summary, description, exercises)`,
        `values (${id(`package-workout:${pkg.id}:${position}`)}, ${packageId}, ${position}, ${text(workout.name)}, ${text(workout.summary)}, ${text(workout.description)}, ${text(JSON.stringify(workout.exercises))}::jsonb)`,
        `on conflict (package_id, position) do update set name = excluded.name, summary = excluded.summary, description = excluded.description, exercises = excluded.exercises;`,
        '',
      );
    });

    for (const comment of pkg.comments) {
      lines.push(
        `insert into public.package_comments (id, package_id, author_name, rating, body, commented_on)`,
        `values (${id(`comment:${pkg.id}:${comment.id}`)}, ${packageId}, ${text(comment.author)}, ${comment.rating}, ${text(comment.text)}, ${text(comment.date)})`,
        `on conflict (id) do update set author_name = excluded.author_name, rating = excluded.rating, body = excluded.body, commented_on = excluded.commented_on;`,
        '',
      );
    }
  });
});

const target = join(__dirname, '..', 'supabase', 'seed.sql');
writeFileSync(target, lines.join('\n'));
console.log(`Wrote ${target}: ${trainers.length} trainers.`);
